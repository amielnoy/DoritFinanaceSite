#!/usr/bin/env node
/**
 * Turns a Base44 entity export into SQL for the Supabase tables.
 *
 *   node scripts/backfill-from-base44.mjs <export.json> > backfill.sql
 *
 * The export holds customer personal data, so it is never committed and never
 * passed through this repo — the path is an argument and the SQL goes to
 * stdout for you to inspect before it touches a database.
 *
 * Re-runnable on purpose. Rows key on `base44_id` and conflicts update rather
 * than fail, because during the dual-write phases the two stores are compared
 * repeatedly and a lead's status may have moved on Base44 since the last pass.
 * Running it twice must converge, not duplicate.
 *
 * Base44 attaches `created_by_id` and `is_sample` to every row; neither is
 * carried over. `created_by_id` names a Base44 user that will not exist after
 * the migration, and `is_sample` marks demo data (none in production today).
 */
import { readFileSync } from "node:fs";

const file = process.argv[2];
if (!file) {
  console.error("usage: backfill-from-base44.mjs <export.json>");
  process.exit(2);
}

/** A SQL literal. NULL for absent, doubled quotes for everything else. */
const q = (v) => {
  if (v === undefined || v === null || v === "") return "NULL";
  if (typeof v === "boolean") return v ? "true" : "false";
  if (typeof v === "number") return String(v);
  return "'" + String(v).replace(/'/g, "''") + "'";
};

/** Which entity becomes which table, and which declared fields come with it. */
const TABLES = {
  Lead: {
    table: "leads",
    cols: ["name","phone","email","source","topic","timing","message","status",
           "escalation_reason","handled_by_agent","consent_version","consent_at"],
  },
  Contact: {
    table: "contacts",
    cols: ["phone","name","email","channel","notes","last_seen"],
  },
  BlogPost: {
    table: "blog_posts",
    cols: ["title","excerpt","body","image_url","tags","published"],
  },
  Testimonial: {
    table: "testimonials",
    cols: ["name","role","quote","image_url","rating","source"],
  },
};

const data = JSON.parse(readFileSync(file, "utf8"));

console.log("-- Generated by scripts/backfill-from-base44.mjs. Do not commit.");
console.log("begin;");
// A faithful load, not an edit: suppress the updated_at trigger for this
// transaction so Base44's timestamps arrive as they are. Without this the
// trigger stamps now() on every conflict-update, and because the backfill is
// re-run through the dual-write phases, the second pass rewrites the history
// the column exists to keep — 2 genuinely modified leads became 25.
// A trigger cannot see whether a column appeared in the SET clause, so this
// has to be decided by the loader rather than by the trigger.
console.log("set local session_replication_role = replica;\n");

let total = 0;
for (const [entity, { table, cols }] of Object.entries(TABLES)) {
  const rows = data[entity] ?? [];
  if (!rows.length) {
    console.log(`-- ${entity}: nothing to import\n`);
    continue;
  }

  const columns = [...cols, "base44_id", "created_at", "updated_at"];
  // `status` carries a NOT NULL default; an explicit NULL would defeat it.
  const updatable = columns.filter((c) => c !== "base44_id");

  console.log(`-- ${entity} → ${table} (${rows.length})`);
  console.log(`insert into public.${table} (${columns.join(", ")}) values`);
  console.log(
    rows
      .map((r) => {
        const vals = cols.map((c) => q(r[c]));
        vals.push(q(r.id), q(r.created_date), q(r.updated_date ?? r.created_date));
        return "  (" + vals.join(", ") + ")";
      })
      .join(",\n")
  );
  console.log(
    `on conflict (base44_id) do update set\n  ` +
      updatable.map((c) => `${c} = excluded.${c}`).join(",\n  ") +
      ";\n"
  );
  total += rows.length;
}

console.log("commit;");
console.error(`${total} rows written to stdout as SQL`);
