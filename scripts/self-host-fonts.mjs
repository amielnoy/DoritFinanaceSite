#!/usr/bin/env node
/**
 * Regenerates the self-hosted fonts: public/fonts/*.woff2, their licences,
 * src/fonts.css (the site) and public/fonts/poa.css (the static POA form).
 *
 * The site used to load these from Google Fonts. That sent every visitor's IP
 * address to Google on every page — something the privacy policy does not
 * mention — and made the e2e suite, which blocks Google Fonts to stay
 * hermetic, render in whatever fallback the CI machine had. Served from our
 * own origin, the fonts are the same for visitors and for the tests.
 *
 * Source: the @fontsource packages (the same OFL files Google serves), fetched
 * with `npm pack` so they never become a runtime dependency. Only the subsets
 * the site's text uses are copied: Hebrew, and basic Latin.
 *
 *   node scripts/self-host-fonts.mjs
 */
import { execFileSync } from "node:child_process";
import { copyFileSync, mkdirSync, mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const ROOT = new URL("..", import.meta.url).pathname;
const OUT = join(ROOT, "public/fonts");

/** [package, family, [weight, style][], subsets] */
const SITE = [
  ["cormorant-garamond", "Cormorant Garamond", [["400", "normal"], ["500", "normal"], ["600", "normal"], ["400", "italic"]], ["latin"]],
  ["frank-ruhl-libre", "Frank Ruhl Libre", [["300", "normal"], ["400", "normal"], ["500", "normal"]], ["hebrew", "latin"]],
  ["lora", "Lora", [["400", "normal"], ["600", "normal"]], ["latin"]],
  ["noto-serif-hebrew", "Noto Serif Hebrew", [["400", "normal"], ["500", "normal"], ["600", "normal"]], ["hebrew", "latin"]],
];
const POA = [
  ["frank-ruhl-libre", "Frank Ruhl Libre", [["500", "normal"], ["700", "normal"]], ["hebrew", "latin"]],
  ["heebo", "Heebo", [["400", "normal"], ["500", "normal"], ["700", "normal"]], ["hebrew", "latin"]],
];

const work = mkdtempSync(join(tmpdir(), "fonts-"));
const unpacked = new Map();
function unpack(pkg) {
  if (unpacked.has(pkg)) return unpacked.get(pkg);
  const tgz = execFileSync("npm", ["pack", "-q", `@fontsource/${pkg}`], { cwd: work, encoding: "utf8" }).trim().split("\n").pop();
  const dir = join(work, pkg);
  mkdirSync(dir);
  execFileSync("tar", ["xzf", join(work, tgz), "-C", dir]);
  const root = join(dir, "package");
  copyFileSync(join(root, "LICENSE"), join(OUT, `LICENSE-${pkg}.txt`));
  unpacked.set(pkg, root);
  return root;
}

/** The @font-face blocks for one weight/style, keeping only the wanted subsets. */
function faces(pkg, weight, style, subsets) {
  const root = unpack(pkg);
  const css = readFileSync(join(root, style === "italic" ? `${weight}-italic.css` : `${weight}.css`), "utf8");
  const blocks = css.split(/(?=\/\* )/).filter((b) => b.includes("@font-face"));
  return subsets.map((subset) => {
    const name = `${pkg}-${subset}-${weight}-${style}`;
    const block = blocks.find((b) => b.startsWith(`/* ${name} */`));
    if (!block) throw new Error(`no ${name} in @fontsource/${pkg}`);
    copyFileSync(join(root, "files", `${name}.woff2`), join(OUT, `${name}.woff2`));
    // woff2 only: every browser the site supports reads it.
    return block.replace(/src: [^;]+;/, `src: url(/fonts/${name}.woff2) format('woff2');`).trim();
  });
}

function sheet(spec, header) {
  const out = [header];
  for (const [pkg, , variants, subsets] of spec) {
    for (const [weight, style] of variants) out.push(...faces(pkg, weight, style, subsets));
  }
  return out.join("\n\n") + "\n";
}

mkdirSync(OUT, { recursive: true });
const banner = (what) =>
  `/* ${what} — generated by scripts/self-host-fonts.mjs; do not edit by hand.\n   Self-hosted so no visitor request goes to Google Fonts. */`;
writeFileSync(join(ROOT, "src/fonts.css"), sheet(SITE, banner("The site's fonts")));
writeFileSync(join(OUT, "poa.css"), sheet(POA, banner("The POA form's fonts")));
console.log("fonts written to public/fonts, src/fonts.css and public/fonts/poa.css");
